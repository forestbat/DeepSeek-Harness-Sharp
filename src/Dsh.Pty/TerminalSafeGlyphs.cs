namespace Dsh.Pty;

/**
 * 东亚宽度 Ambiguous(EAW=A)的字符在部分终端/字体(简中控制台尤为常见)下按两格渲染,
 * 而 TerminalTextWidth 按一格计入布局: 一行里每个这类字符都让光标多走一格, 行尾超宽换行后整帧撕裂,
 * 表现为分屏分隔线/浮层边框/状态栏错位。
 * 这里把落屏字节里的这类字符换成等宽 ASCII —— 网格与布局仍保留原字形(宽度模型不变), 只有 ANSI 输出变窄。
 * 已在宽度模型里记为宽(IsWide)的字符本身与终端一致, 原样保留, 换掉它们反而会让两格单元对不上。
 * 未列入的稀有歧义字符保持原样, 以免过度改写正文。
 */
public static class TerminalSafeGlyphs
{
    public static char AsciiSafe(char character)
    {
        if (character < '\u00a1' || TerminalTextWidth.IsWide(character))
            return character;
        return character switch
        {
            // 常用标点: 破折号/引号/项目符号/省略号等
            >= '\u2010' and <= '\u2015' => '-',
            '\u2018' or '\u2019' or '\u201a' or '\u201b' => '\'',
            '\u201c' or '\u201d' or '\u201e' or '\u201f' => '"',
            '\u2020' or '\u2021' => '+',
            '\u2022' or '\u2023' or '\u2043' => '*',
            >= '\u2024' and <= '\u2026' => '.',
            '\u2027' => '-',
            '\u2030' => '%',
            '\u2032' or '\u2033' or '\u2035' => '\'',
            '\u203b' => '+',
            '\u203e' => '~',
            >= '\u2047' and <= '\u2049' => '?',

            // 箭头
            '\u2190' or '\u2194' or '\u21d0' or '\u21d4' => '<',
            '\u2191' => '^',
            '\u2192' or '\u21b3' or '\u21b4' or '\u21d2' or '\u21e8' => '>',
            '\u2193' => 'v',
            >= '\u2195' and <= '\u21ff' => '>',

            // 数学运算符
            '\u2202' => 'd',
            '\u2207' => 'V',
            '\u2208' => 'e',
            '\u220b' => 'E',
            '\u220f' => 'P',
            '\u2211' => 'S',
            '\u2215' => '/',
            '\u221a' => 'v',
            '\u221d' or '\u222e' or '\u2295' or '\u2299' => 'o',
            '\u2223' or '\u2225' => '|',
            '\u2227' or '\u2229' => '^',
            '\u2228' or '\u222a' => 'v',
            '\u2234' or '\u2235' => ':',
            '\u223c' or '\u2248' => '~',
            '\u2260' or '\u2261' => '=',
            '\u2264' or '\u2266' or '\u2282' or '\u2286' => '<',
            '\u2265' or '\u2267' or '\u2283' or '\u2287' => '>',
            '\u22a5' or '\u22bf' => 'T',
            >= '\u2200' and <= '\u22ff' => '?',

            // 带圈字符
            >= '\u2460' and <= '\u2468' => (char)('1' + (character - '\u2460')),
            >= '\u2469' and <= '\u2473' => '#',
            '\u24ea' => '0',
            >= '\u2474' and <= '\u24ff' => '#',

            // 制表线
            '\u2500' or '\u2501' or '\u254c' or '\u254d' => '-',
            '\u2502' or '\u2503' or '\u254e' or '\u254f' => '|',
            >= '\u2504' and <= '\u257f' => '+',

            // 方块元素
            '\u2580' or '\u2594' => '^',
            >= '\u2581' and <= '\u2587' => '_',
            '\u2588' => '#',
            >= '\u2589' and <= '\u2590' => '|',
            '\u2591' => '.',
            '\u2592' => ':',
            '\u2593' => '#',
            >= '\u2595' and <= '\u259f' => '#',

            // 几何图形
            '\u25a0' or '\u25a1' or '\u25aa' or '\u25ab' or '\u25c6' or '\u25c7' or '\u25c8' or '\u25c9' => '#',
            '\u25b2' or '\u25b3' or '\u25b4' or '\u25b5' => '^',
            >= '\u25b6' and <= '\u25ba' => '>',
            '\u25bc' or '\u25bd' or '\u25be' or '\u25bf' => 'v',
            >= '\u25c0' and <= '\u25c5' => '<',
            '\u25cb' or '\u25e6' or '\u25ef' => 'o',
            '\u25cf' => '*',
            >= '\u25a0' and <= '\u25ff' => '*',

            // 杂项符号
            '\u2605' or '\u2606' or '\u2699' => '*',
            '\u2609' or '\u260e' or '\u2640' or '\u2642' => 'o',
            '\u261e' => '>',
            '\u26a0' => '!',
            >= '\u2600' and <= '\u26ff' => '+',

            // 装饰符号
            '\u2713' or '\u2714' => '+',
            '\u2716' or '\u2717' or '\u2718' => 'x',
            '\u276e' => '<',
            '\u276f' => '>',
            >= '\u2700' and <= '\u27bf' => '*',

            // Latin-1 中的歧义标点(字母不加改动, 以免破坏正文)
            '\u00a1' => '!',
            '\u00a4' => '$',
            '\u00a7' => 'S',
            '\u00a8' => '"',
            '\u00aa' => 'a',
            '\u00ad' => '-',
            '\u00ae' => 'R',
            >= '\u00b0' and <= '\u00b4' => '\'',
            '\u00b6' => 'P',
            '\u00b7' => '-',
            '\u00b8' => ',',
            '\u00b9' => '1',
            '\u00ba' => 'o',
            '\u00bb' => '>',
            >= '\u00bc' and <= '\u00be' => '?',
            '\u00bf' => '?',
            '\u00d7' => 'x',
            '\u00f7' => '/',

            _ => character
        };
    }
}
